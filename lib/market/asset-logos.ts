export function assetLogoPath(symbol: string): string | undefined {
  const ticker = symbol.trim().toUpperCase();
  const type = Object.hasOwn(ASSET_LOGO_FILES, ticker) ? ASSET_LOGO_FILES[ticker] : undefined;
  return type ? `/logos/${ticker}.${type}` : undefined;
}
